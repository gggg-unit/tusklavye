def tr(key: str, **kwargs) -> str:
    """Translate a key to the current language, with optional format args."""
    text = _STRINGS.get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text